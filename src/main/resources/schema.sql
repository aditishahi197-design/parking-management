-- Reference schema for PostgreSQL. Hibernate creates/updates tables in the default setup.
-- If using this script to initialize a database manually, set spring.jpa.hibernate.ddl-auto=validate.
CREATE TABLE IF NOT EXISTS parking_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_number VARCHAR(20) NOT NULL UNIQUE,
    occupied BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS vehicle_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(20) NOT NULL,
    slot_id BIGINT NOT NULL REFERENCES parking_slots(id),
    entry_time TIMESTAMP NOT NULL,
    exit_time TIMESTAMP,
    amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
);

CREATE INDEX IF NOT EXISTS idx_booking_exit_time ON vehicle_bookings(exit_time);
CREATE INDEX IF NOT EXISTS idx_booking_vehicle ON vehicle_bookings(vehicle_number);
